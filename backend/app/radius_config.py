def render_client(c: Client) -> str:
    lines = [f"client {c.name} {{"]
    lines.append(f"{INDENT}ipaddr = {c.ipaddr}")
    lines.append(f"{INDENT}secret = {_quote_secret(c.secret)}")
    lines.append(f"{INDENT}shortname = {c.shortname or c.name}")
    lines.append(f"{INDENT}nastype = {c.nas_type}")
    if c.proto and c.proto != "udp":
        lines.append(f"{INDENT}proto = {c.proto}")
    lines.append(
        f"{INDENT}require_message_authenticator = "
        f"{c.require_message_authenticator}"
    )
    # Custom field read by policy.d/radiuspanel via %{client:preserve_source_ip}.
    if c.preserve_source_ip:
        lines.append(f"{INDENT}preserve_source_ip = yes")
    lines.append("}")
    return "\n".join(lines)


async def render_clients_conf(db: AsyncSession) -> str:
    rows = (
        await db.execute(
            select(Client).where(Client.enabled).order_by(Client.name)
        )
    ).scalars().all()
    parts = [CLIENTS_HEADER.format(ts=datetime.now(timezone.utc).isoformat())]
    if not rows:
        parts.append("# WARNING: no clients defined — FreeRADIUS will drop all\n"
                     "# incoming requests (every source is an unknown client).\n")
    for c in rows:
        parts.append(render_client(c))
        parts.append("")
    return "\n".join(parts).rstrip() + "\n"


