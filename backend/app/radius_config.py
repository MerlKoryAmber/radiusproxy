"""proxy.conf renderer + validate/apply pipeline (FreeRADIUS 3.2.x).

This module is the heart of the panel. It turns the DB records into a valid
FreeRADIUS 3.2 proxy.conf, optionally validates it with `radiusd -XC`, writes
it to the configured path and reloads the server.

Keeping all FreeRADIUS-specific syntax in one place means porting to
FreeRADIUS 4 (where proxy.conf is replaced by rlm_radius instances) is a matter
of swapping this renderer, not touching the API or the data model.
"""
from __future__ import annotations

import asyncio
import os
import shlex
from dataclasses import dataclass
from datetime import datetime, timezone
from pathlib import Path

from sqlalchemy import select
from sqlalchemy.ext.asyncio import AsyncSession
from sqlalchemy.orm import selectinload

from .config import get_settings
from .models import HomeServer, HomeServerPool, LdapSettings, PoolMember, Realm

settings = get_settings()

INDENT = "\t"


def _quote_secret(secret: str) -> str:
    """Wrap the shared secret in double quotes, escaping as FreeRADIUS expects."""
    escaped = secret.replace("\\", "\\\\").replace('"', '\\"')
    return f'"{escaped}"'


def render_home_server(hs: HomeServer) -> str:
    lines = [f"home_server {hs.name} {{"]
    lines.append(f"{INDENT}type = {hs.type}")
    lines.append(f"{INDENT}ipaddr = {hs.ipaddr}")
    lines.append(f"{INDENT}port = {hs.port}")
    lines.append(f"{INDENT}secret = {_quote_secret(hs.secret)}")
    lines.append(
        f"{INDENT}require_message_authenticator = "
        f"{'yes' if hs.require_message_authenticator else 'no'}"
    )
    lines.append(f"{INDENT}response_window = {hs.response_window}")
    lines.append(f"{INDENT}zombie_period = {hs.zombie_period}")
    lines.append(f"{INDENT}revive_interval = {hs.revive_interval}")
    if hs.status_check and hs.status_check != "none":
        lines.append(f"{INDENT}status_check = {hs.status_check}")
        lines.append(f"{INDENT}check_interval = {hs.check_interval}")
        lines.append(f"{INDENT}num_answers_to_alive = 3")
    else:
        lines.append(f"{INDENT}status_check = none")
    lines.append("}")
    return "\n".join(lines)


def render_pool(pool: HomeServerPool, member_names: list[str]) -> str:
    lines = [f"home_server_pool {pool.name} {{"]
    lines.append(f"{INDENT}type = {pool.type}")
    if not member_names:
        lines.append(f"{INDENT}# WARNING: pool has no home_server members")
    for name in member_names:
        lines.append(f"{INDENT}home_server = {name}")
    lines.append("}")
    return "\n".join(lines)


def render_realm(realm: Realm, auth_pool: str | None, acct_pool: str | None) -> str:
    lines = [f"realm {realm.name} {{"]
    if auth_pool and acct_pool and auth_pool == acct_pool:
        lines.append(f"{INDENT}pool = {auth_pool}")
    else:
        if auth_pool:
            lines.append(f"{INDENT}auth_pool = {auth_pool}")
        if acct_pool:
            lines.append(f"{INDENT}acct_pool = {acct_pool}")
    if not auth_pool and not acct_pool:
        lines.append(f"{INDENT}# WARNING: realm has no pool assigned")
    if realm.nostrip:
        lines.append(f"{INDENT}nostrip")
    lines.append("}")
    return "\n".join(lines)


def _quote(value: str) -> str:
    """Single-quote a value for FreeRADIUS, escaping embedded quotes."""
    escaped = value.replace("\\", "\\\\").replace("'", "\\'")
    return f"'{escaped}'"


PASSWORD_MASK = "********"

LDAP_HEADER = """#
# mods-enabled/ldap — generated by FreeRADIUS Proxy Panel
# Generated: {ts}
#
# DO NOT EDIT BY HAND. Overwritten on the next apply.
# Target: FreeRADIUS 3.2.x (rlm_ldap). AD group gate — see docs/adr/0001.
#
"""


def render_ldap_module(cfg: LdapSettings, *, mask_password: bool = False) -> str:
    """Render the AD/LDAP module (mods-enabled/ldap) for the group gate.

    When `mask_password` is True the bind password is replaced with a mask —
    used for the UI preview so the secret is never shipped to the browser.
    """
    scheme = "ldaps://" if cfg.use_ldaps else ""
    port = cfg.port or (636 if cfg.use_ldaps else 389)
    password = PASSWORD_MASK if mask_password else cfg.bind_password

    lines = [LDAP_HEADER.format(ts=datetime.now(timezone.utc).isoformat())]
    lines.append("ldap {")
    lines.append(f"{INDENT}server = {_quote(scheme + cfg.server)}")
    lines.append(f"{INDENT}port = {port}")
    lines.append(f"{INDENT}identity = {_quote(cfg.bind_dn)}")
    lines.append(f"{INDENT}password = {_quote(password)}")
    lines.append(f"{INDENT}base_dn = {_quote(cfg.base_dn)}")
    lines.append("")
    lines.append(f"{INDENT}# group membership check — per-realm required group")
    lines.append(f"{INDENT}group {{")
    group_base = cfg.group_base_dn or cfg.base_dn
    lines.append(f"{INDENT}{INDENT}base_dn = {_quote(group_base)}")
    lines.append(f"{INDENT}{INDENT}filter = {_quote(cfg.group_filter)}")
    lines.append(
        f"{INDENT}{INDENT}membership_attribute = "
        f"{_quote(cfg.group_membership_attribute)}"
    )
    # Cache the resolved membership so we don't hit AD on every packet.
    lines.append(f"{INDENT}{INDENT}cacheable_name = yes")
    lines.append(f"{INDENT}}}")
    lines.append("")
    lines.append(f"{INDENT}options {{")
    lines.append(f"{INDENT}{INDENT}net_timeout = {cfg.net_timeout}")
    lines.append(f"{INDENT}{INDENT}timeout = {cfg.net_timeout}")
    lines.append(f"{INDENT}{INDENT}res_timeout = {cfg.net_timeout}")
    lines.append(f"{INDENT}}}")
    if cfg.start_tls and not cfg.use_ldaps:
        lines.append("")
        lines.append(f"{INDENT}tls {{")
        lines.append(f"{INDENT}{INDENT}start_tls = yes")
        lines.append(f"{INDENT}}}")
    lines.append(f"{INDENT}# membership cache TTL (s): {cfg.cache_ttl}")
    lines.append("}")
    return "\n".join(lines) + "\n"


HEADER = """#
# proxy.conf — generated by FreeRADIUS Proxy Panel
# Generated: {ts}
#
# DO NOT EDIT BY HAND. Changes made here are overwritten on the next apply.
# Target: FreeRADIUS 3.2.x
#
"""


async def render_proxy_conf(db: AsyncSession) -> str:
    """Build the full proxy.conf text from the current DB state."""
    hs_rows = (
        await db.execute(
            select(HomeServer).where(HomeServer.enabled).order_by(HomeServer.name)
        )
    ).scalars().all()

    pool_rows = (
        await db.execute(
            select(HomeServerPool)
            .where(HomeServerPool.enabled)
            .options(
                selectinload(HomeServerPool.members).selectinload(
                    PoolMember.home_server
                )
            )
            .order_by(HomeServerPool.name)
        )
    ).scalars().all()

    realm_rows = (
        await db.execute(
            select(Realm)
            .where(Realm.enabled)
            .options(selectinload(Realm.auth_pool), selectinload(Realm.acct_pool))
            .order_by(Realm.name)
        )
    ).scalars().all()

    parts: list[str] = [HEADER.format(ts=datetime.now(timezone.utc).isoformat())]

    parts.append("# ---- home servers ----\n")
    for hs in hs_rows:
        parts.append(render_home_server(hs))
        parts.append("")

    parts.append("# ---- home server pools ----\n")
    for pool in pool_rows:
        ordered = sorted(pool.members, key=lambda m: m.position)
        names = [m.home_server.name for m in ordered if m.home_server.enabled]
        parts.append(render_pool(pool, names))
        parts.append("")

    parts.append("# ---- realms ----\n")
    for realm in realm_rows:
        auth = realm.auth_pool.name if realm.auth_pool else None
        acct = realm.acct_pool.name if realm.acct_pool else None
        parts.append(render_realm(realm, auth, acct))
        parts.append("")

    return "\n".join(parts).rstrip() + "\n"


@dataclass
class ApplyResult:
    written_path: str
    validated: bool
    validation_output: str
    reloaded: bool
    reload_output: str


async def _run(cmd: str) -> tuple[int, str]:
    proc = await asyncio.create_subprocess_exec(
        *shlex.split(cmd),
        stdout=asyncio.subprocess.PIPE,
        stderr=asyncio.subprocess.STDOUT,
    )
    out, _ = await proc.communicate()
    return proc.returncode or 0, out.decode(errors="replace")


class ConfigValidationError(Exception):
    def __init__(self, output: str):
        super().__init__("FreeRADIUS rejected the generated config")
        self.output = output


async def apply_proxy_conf(db: AsyncSession) -> ApplyResult:
    """Render, write, (optionally) validate, and (optionally) reload.

    `radiusd -XC` validates the whole server config, and proxy.conf is included
    by its real path — so we must validate the *actual* target file, not a
    side-copy. To stay safe we back up the current file, write the new one,
    validate it, and roll back to the backup if validation fails. The running
    server is untouched until the reload step, which only runs after a pass.
    """
    content = await render_proxy_conf(db)
    target = Path(settings.proxy_conf_path)
    target.parent.mkdir(parents=True, exist_ok=True)

    had_previous = target.exists()
    backup = target.read_text() if had_previous else None

    # Write the new file in place so the validator reads the real content.
    target.write_text(content)

    validated = False
    validation_output = "validation skipped (RADIUS_CHECK_CMD not set)"
    if settings.radius_check_cmd:
        code, out = await _run(settings.radius_check_cmd)
        validation_output = out
        if code != 0:
            # Roll back to the last known-good file (or remove ours).
            if had_previous:
                target.write_text(backup or "")
            else:
                os.unlink(target)
            raise ConfigValidationError(out)
        validated = True

    reloaded = False
    reload_output = "reload skipped (RADIUS_RELOAD_CMD not set)"
    if settings.radius_reload_cmd:
        code, out = await _run(settings.radius_reload_cmd)
        reload_output = out
        reloaded = code == 0

    return ApplyResult(
        written_path=str(target),
        validated=validated,
        validation_output=validation_output,
        reloaded=reloaded,
        reload_output=reload_output,
    )
