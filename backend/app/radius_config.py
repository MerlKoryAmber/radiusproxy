async def _fallback_pool_names(db: AsyncSession) -> set[str]:
    """Pool names with an enabled `pool_down_fallback` rule — only when AD/LDAP
    is on (the fallback binds against it). Empty otherwise (feature off)."""
    ldap_cfg = await db.get(LdapSettings, 1)
    if not (ldap_cfg and ldap_cfg.enabled):
        return set()
    rows = (
        await db.execute(
            select(Rule)
            .where(Rule.enabled, Rule.pool_down_fallback)
            .options(selectinload(Rule.target_pool))
        )
    ).scalars().all()
    return {r.target_pool.name for r in rows if r.target_pool}


FALLBACK_SITE_HEADER = """#
# sites-enabled/radiuspanel-fallback — generated by FreeRADIUS Proxy Panel
# Generated: {ts}
#
# DO NOT EDIT BY HAND. Overwritten on the next apply.
# 2FA pool-down fallback (ADR-0009): when a target pool is fully dead, check the
# 1st factor (AD password, PAP) locally and ACCEPT. Deliberate 2FA bypass on
# outage — enabled per rule. Reached via home_server_pool "fallback".
#
"""


async def render_fallback_site() -> str:
    """The fallback virtual server. Gated by SQL so only clients with an enabled
    pool_down_fallback rule are let through; then AD user lookup + password bind."""
    i = INDENT
    gate = (
        "%{sql:SELECT 1 FROM rules r JOIN clients c ON c.id = r.client_id "
        "WHERE r.enabled AND r.pool_down_fallback "
        "AND c.shortname = '%{Client-Shortname}' LIMIT 1}"
    )
    # The fallback logs its own decision row directly (radiuspanel_log) with a
    # pool-down-* marker, so a 2FA bypass is always visible in Logs even though
    # the main server also records the proxied outcome.
    return FALLBACK_SITE_HEADER.format(ts=datetime.now(timezone.utc).isoformat()) + (
        f"server {FALLBACK_VSERVER} {{\n"
        f"{i}authorize {{\n"
        f'{i}{i}if ("{gate}" != "1") {{\n'
        f'{i}{i}{i}update request {{ &Tmp-String-1 := "pool-down-blocked" }}\n'
        f"{i}{i}{i}reject\n"
        f"{i}{i}}}\n"
        f"{i}{i}ldap\n"
        f"{i}{i}if (notfound || fail) {{\n"
        f'{i}{i}{i}update request {{ &Tmp-String-1 := "pool-down-nouser" }}\n'
        f"{i}{i}{i}reject\n"
        f"{i}{i}}}\n"
        f"{i}{i}if (!&control:Auth-Type) {{\n"
        f"{i}{i}{i}update control {{ &Auth-Type := LDAP }}\n"
        f"{i}{i}}}\n"
        f"{i}}}\n"
        f"{i}authenticate {{\n"
        f"{i}{i}Auth-Type LDAP {{\n"
        f"{i}{i}{i}ldap\n"
        f"{i}{i}}}\n"
        f"{i}}}\n"
        f"{i}post-auth {{\n"
        f'{i}{i}update request {{ &Tmp-String-1 := "pool-down-1fa" }}\n'
        f"{i}{i}radiuspanel_log\n"
        f"{i}{i}Post-Auth-Type REJECT {{\n"
        f'{i}{i}{i}update request {{ &Tmp-String-1 := "pool-down-reject" }}\n'
        f"{i}{i}{i}radiuspanel_log\n"
        f"{i}{i}}}\n"
        f"{i}}}\n"
        "}\n"
    )


async def render_proxy_conf(db: AsyncSession) -> str:
    """Build the full proxy.conf text from the current DB state.

    Routing is per-client (ADR-0003): one realm is generated per pool as proxy
    plumbing; the panel picks it via Proxy-To-Realm (radiuspanel_route), not by
    User-Name suffix.
    """
    ts_rows = (
        await db.execute(
            select(TargetServer)
            .where(TargetServer.enabled)
            .order_by(TargetServer.name)
        )
    ).scalars().all()

    pool_rows = (
        await db.execute(
            select(HomeServerPool)
            .where(HomeServerPool.enabled)
            .options(
                selectinload(HomeServerPool.members).selectinload(
                    PoolMember.target_server
                )
            )
            .order_by(HomeServerPool.name)
        )
    ).scalars().all()

    fb_pools = await _fallback_pool_names(db)

    parts: list[str] = [HEADER.format(ts=datetime.now(timezone.utc).isoformat())]

    parts.append("# ---- target servers ----\n")
    for ts in ts_rows:
        parts.append(render_home_server(ts))
        parts.append("")

    # Virtual home server for the 2FA pool-down fallback (local AD 1st factor).
    if fb_pools:
        parts.append(
            f"home_server {FALLBACK_HOME_SERVER} {{\n"
            f"{INDENT}virtual_server = {FALLBACK_VSERVER}\n"
            "}\n"
        )

    parts.append("# ---- pools ----\n")
    for pool in pool_rows:
        ordered = sorted(pool.members, key=lambda m: m.position)
        names = [m.target_server.name for m in ordered if m.target_server.enabled]
        parts.append(render_pool(pool, names, fallback=pool.name in fb_pools))
        parts.append("")

    parts.append("# ---- realms (one per pool; routing chosen per client) ----\n")
    for pool in pool_rows:
        parts.append(render_realm_for_pool(pool.name))
        parts.append("")

    return "\n".join(parts).rstrip() + "\n"


@dataclass
class ApplyResult:
    written_paths: list[str]
    validated: bool
    validation_output: str
    reloaded: bool
    reload_output: str


def _run_blocking(cmd: str) -> tuple[int, str]:
    proc = subprocess.run(
        shlex.split(cmd),
        stdout=subprocess.PIPE,
        stderr=subprocess.STDOUT,
        text=True,
    )
    return proc.returncode, proc.stdout


async def _run(cmd: str) -> tuple[int, str]:
    # Run in a worker thread via subprocess.run rather than
    # asyncio.create_subprocess_exec: under uvicorn's uvloop the asyncio child
    # watcher interacts badly with FreeRADIUS's double-forking daemon (apply
    # would take minutes / hang). A thread + blocking subprocess is reliable.
    return await asyncio.to_thread(_run_blocking, cmd)


class ConfigValidationError(Exception):
    def __init__(self, output: str):
        super().__init__("FreeRADIUS rejected the generated config")
        self.output = output


@dataclass
class _Backup:
    path: Path
    existed: bool
    content: str | None


def _write_with_backup(path: Path, content: str) -> _Backup:
    """Write `content` to `path`, returning enough state to roll back."""
    path.parent.mkdir(parents=True, exist_ok=True)
    existed = path.exists()
    backup = path.read_text() if existed else None
    path.write_text(content)
    return _Backup(path=path, existed=existed, content=backup)


def _rollback(backups: list[_Backup]) -> None:
    for b in backups:
        if b.existed:
            b.path.write_text(b.content or "")
        elif b.path.exists():
            os.unlink(b.path)


async def apply_config(db: AsyncSession) -> ApplyResult:
    """Render every managed file, write in place, validate once, roll back all
    on failure, then reload.

    The panel owns several FreeRADIUS files (proxy.conf, clients.conf, …).
    `radiusd -XC` validates the whole server config by its real paths, so we
    must write the *actual* target files, not side-copies. All files are backed
    up first; a validation failure rolls back every one of them, leaving the
    running server on its last known-good config until the reload step, which
    only runs after a pass.
    """
    targets: list[tuple[Path, str]] = [
        (Path(settings.proxy_conf_path), await render_proxy_conf(db)),
        (Path(settings.clients_conf_path), await render_clients_conf(db)),
        (Path(settings.policy_conf_path), await render_policy_conf(db)),
    ]

    # AD/LDAP module is written only when enabled. Its CA cert (if any) is
    # materialised first so the module's ca_file points at a real file.
    ldap_cfg = await db.get(LdapSettings, 1)
    if ldap_cfg and ldap_cfg.enabled:
        if ldap_cfg.ca_cert.strip():
            targets.append((Path(settings.ldap_ca_path), ldap_cfg.ca_cert))
        targets.append(
            (Path(settings.ldap_conf_path), render_ldap_module(ldap_cfg))
        )

    # The sql module is always written: the adgate uses it for membership and
    # radiuspanel_log uses it for the decision log. It points at the panel's own
    # Postgres, which is always up alongside the backend.
    targets.append((Path(settings.sql_conf_path), render_sql_module()))

    # Patch only the max_request_time line in the (stock) radiusd.conf from
    # RadiusSettings — it caps a target's response_window, so slow 2FA needs it
    # raised. Skip if the file or the setting isn't there (dev without raddb).
    radiusd_path = Path(settings.radiusd_conf_path)
    rad_cfg = await db.get(RadiusSettings, 1)
    if rad_cfg and radiusd_path.exists():
        cur = radiusd_path.read_text()
        patched = re.sub(
            r"(?m)^(\s*)max_request_time\s*=.*$",
            rf"\g<1>max_request_time = {int(rad_cfg.max_request_time)}",
            cur,
            count=1,
        )
        if patched != cur:
            targets.append((radiusd_path, patched))

    # 2FA pool-down fallback virtual server (ADR-0009): write when any rule
    # enables it (+ AD on); otherwise remove a stale file so -XC stays clean.
    fb_pools = await _fallback_pool_names(db)
    fb_path = Path(settings.fallback_site_path)
    if fb_pools:
        targets.append((fb_path, await render_fallback_site()))

    backups = [_write_with_backup(path, content) for path, content in targets]
    if not fb_pools and fb_path.exists():
        backups.append(_Backup(path=fb_path, existed=True, content=fb_path.read_text()))
        fb_path.unlink()

    validated = False
    validation_output = "validation skipped (RADIUS_CHECK_CMD not set)"
    if settings.radius_check_cmd:
        code, out = await _run(settings.radius_check_cmd)
        validation_output = out
        if code != 0:
            _rollback(backups)
            raise ConfigValidationError(out)
        validated = True

    reloaded = False
    reload_output = "reload skipped (RADIUS_RELOAD_CMD not set)"
    if settings.radius_reload_cmd:
        code, out = await _run(settings.radius_reload_cmd)
        reload_output = out
        reloaded = code == 0

    return ApplyResult(
        written_paths=[str(p) for p, _ in targets],
        validated=validated,
        validation_output=validation_output,
        reloaded=reloaded,
        reload_output=reload_output,
    )
